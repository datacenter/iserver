    def print_machine_configs_ssh(self, info, cluster_name=None, title=False):
        if title:
            if cluster_name is None:
                self.my_output.default(
                    'OpenShift ssh public keys access',
                    underline=True,
                    before_newline=True
                )
            else:
                self.my_output.default(
                    'OpenShift [%s] ssh public keys access' % (cluster_name),
                    underline=True,
                    before_newline=True
                )

        users = {}
        for item in info:
            (key_type, key, user) = item['key'].split(' ')
            if user not in users:
                users[user] = {}
                users[user]['user'] = user
                users[user]['key'] = '%s...%s' % (key[:10], key[-10:])
                users[user]['type'] = key_type
                users[user]['node'] = []

            if item['mc'] == '99-master-ssh':
                if 'master' not in users[user]['node']:
                    users[user]['node'].append('master')

            if item['mc'] == '99-worker-ssh':
                if 'worker' not in users[user]['node']:
                    users[user]['node'].append('worker')

        users_list = []
        for user in users:
            users_list.append(
                users[user]
            )

        order = [
            'user',
            'type',
            'key',
            'node'
        ]

        headers = [
            'Id',
            'Type',
            'Key',
            'Node'
        ]

        self.my_output.my_table(
            users_list,
            order=order,
            headers=headers,
            allow_order_subkeys=True,
            underline=True,
            row_separator=True,
            table=True
        )
